#!/usr/bin/env python3
"""Keep generated registrations in sync with the services on disk (idempotent).

* root pyproject.toml     -> workspace members block
* apps/monolith/pyproject -> service dependency + source blocks
* .importlinter           -> fully generated architecture contracts (docs/architecture/STANDARDS.md §8)
* docker-compose.yml      -> migrate-<service> jobs + the app's env / depends_on entries (rule E-1);
                             a service adds container env in services/<name>/service/compose.env
* deploy/postgres/provision.sql -> one role + one schema per service (rule D-4)

  uv run python tools/sync_workspace.py           # rewrite
  uv run python tools/sync_workspace.py --check   # exit 1 if anything would change (CI)
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

LIBS = [
    "platform_core",
    "platform_events",
    "platform_http",
    "platform_observability",
    "platform_security",
]
EXTERNALS = ["fastapi", "sqlalchemy", "httpx", "redis"]


def discover_services(root: Path) -> list[str]:
    services_dir = root / "services"
    if not services_dir.exists():
        return []
    return sorted(
        d.name
        for d in services_dir.iterdir()
        if (d / "service" / "pyproject.toml").exists()
        and (d / "contracts" / "pyproject.toml").exists()
    )


def replace_block(text: str, marker: str, lines: list[str]) -> str:
    pattern = re.compile(
        rf"(?P<indent>[ \t]*)# >>> generated:{re.escape(marker)}[^\n]*\n.*?(?P=indent)# <<< generated:{re.escape(marker)}",
        re.DOTALL,
    )
    match = pattern.search(text)
    if match is None:
        raise SystemExit(f"Marker 'generated:{marker}' not found")
    indent = match.group("indent")
    begin = text[match.start() : text.index("\n", match.start())].rstrip("\n")
    body = "".join(f"{indent}{line}\n" for line in lines)
    return (
        text[: match.start()]
        + begin
        + "\n"
        + body
        + f"{indent}# <<< generated:{marker}"
        + text[match.end() :]
    )


def render_importlinter(services: list[str]) -> str:
    svc = [f"{s}_service" for s in services]
    contracts = [f"{s}_contracts" for s in services]
    apis = [f"{s}_api" for s in services]
    roots = [*LIBS, "monolith_app", *svc, *contracts, *apis, *EXTERNALS]

    def block(items: list[str], indent: int = 4) -> str:
        return "\n".join(" " * indent + i for i in items)

    out: list[str] = [
        "# GENERATED by tools/sync_workspace.py — do not edit. See docs/architecture/STANDARDS.md §8.",
        "[importlinter]",
        "root_packages =",
        block(roots),
        "include_external_packages = True",
        "",
    ]

    def contract(cid: str, name: str, ctype: str, **fields: str | list[str]) -> None:
        out.append(f"[importlinter:contract:{cid}]")
        out.append(f"name = {name}")
        out.append(f"type = {ctype}")
        for key, value in fields.items():
            if isinstance(value, list):
                out.append(f"{key} =")
                out.append(block(value))
            else:
                out.append(f"{key} = {value}")
        out.append("")

    if len(svc) >= 2:
        contract(
            "services-independent",
            "B-1: services never import each other's implementation",
            "independence",
            modules=svc,
        )
    if svc:
        contract(
            "services-not-apps",
            "B-3/B-4: services never import composition roots",
            "forbidden",
            source_modules=svc + contracts,
            forbidden_modules=["monolith_app", *apis],
        )
        contract(
            "contracts-pure",
            "B-2: contracts never directly import frameworks or implementations",
            "forbidden",
            source_modules=contracts,
            forbidden_modules=["fastapi", "sqlalchemy", *svc],
            allow_indirect_imports="True",
        )
    contract(
        "libs-independent",
        "B-3: libs never import services, contracts or apps",
        "forbidden",
        source_modules=LIBS,
        forbidden_modules=[*svc, *contracts, *apis, "monolith_app"],
    )
    for s in services:
        pkg = f"{s}_service"
        contract(
            f"{s}-layers",
            f"L-1: {pkg} layering (api|infrastructure > application > domain)",
            "layers",
            layers=["api | infrastructure", "application", "domain"],
            containers=pkg,
            exhaustive="False",
        )
        contract(
            f"{s}-pure-core",
            f"L-2/L-3: {pkg} domain and application never directly import frameworks or vendors",
            "forbidden",
            source_modules=[f"{pkg}.domain", f"{pkg}.application"],
            forbidden_modules=["fastapi", "sqlalchemy", "httpx", "redis"],
            allow_indirect_imports="True",
        )
    return "\n".join(out).rstrip() + "\n"


def db_url(service: str) -> str:
    """Local-only credentials: role == schema == password == service name (rule D-4)."""
    return f"postgresql+asyncpg://{service}:{service}@postgres:5432/${{POSTGRES_DB:-befastapi}}"


def render_provision_sql(services: list[str]) -> str:
    out = [
        "-- GENERATED by tools/sync_workspace.py - do not edit. Idempotent; runs on every `docker compose up`.",
        "-- One role + one schema per service (docs/architecture/STANDARDS.md D-1..D-4). LOCAL-ONLY passwords.",
        "CREATE EXTENSION IF NOT EXISTS pg_stat_statements;",
        "",
    ]
    for s in services:
        out += [
            f"-- {s}",
            "DO $$ BEGIN",
            f"  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{s}') THEN",
            f"    CREATE ROLE {s} LOGIN PASSWORD '{s}';",
            "  END IF;",
            "END $$;",
            f"CREATE SCHEMA IF NOT EXISTS {s} AUTHORIZATION {s};",
            f"ALTER ROLE {s} SET search_path = {s};",
            "",
        ]
    return "\n".join(out).rstrip() + "\n"


def read_compose_env(root: Path, service: str) -> list[tuple[str, str]]:
    """KEY=VALUE lines from services/<name>/service/compose.env (a service declares its own container env)."""
    path = root / "services" / service / "service" / "compose.env"
    if not path.exists():
        return []
    pairs: list[tuple[str, str]] = []
    for number, raw in enumerate(path.read_text().splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep or not re.fullmatch(r"[A-Z][A-Z0-9_]*", key.strip()):
            raise SystemExit(
                f"{path}:{number}: expected KEY=VALUE with an UPPER_CASE key, got {raw!r}"
            )
        pairs.append((key.strip(), value.strip()))
    return pairs


def compose_blocks(services: list[str], root: Path | None = None) -> dict[str, list[str]]:
    migrate: list[str] = []
    env: list[str] = []
    depends: list[str] = []
    for s in services:
        migrate += [
            f"migrate-{s}:",
            "  <<: *migrate",
            f'  command: ["alembic", "-c", "services/{s}/service/migrations/alembic.ini", "upgrade", "head"]',
            "  environment:",
            f"    {s.upper()}_DATABASE_URL: {db_url(s)}",
            "",
        ]
        env.append(f"{s.upper()}_DATABASE_URL: {db_url(s)}")
        for key, value in read_compose_env(root, s) if root else []:
            env.append(
                f"{key}: {json.dumps(value)}"
            )  # JSON strings are valid YAML double-quoted scalars
        depends += [f"migrate-{s}:", "  condition: service_completed_successfully"]
    return {"migrate-jobs": migrate[:-1] if migrate else [], "app-env": env, "app-depends": depends}


def sync(root: Path, *, check: bool) -> bool:
    services = discover_services(root)
    changed: list[str] = []

    def write(path: Path, content: str) -> None:
        current = path.read_text() if path.exists() else ""
        if current != content:
            changed.append(str(path.relative_to(root)))
            if not check:
                path.write_text(content)

    root_pp = root / "pyproject.toml"
    members = [
        item
        for s in services
        for item in (f'"services/{s}/service",', f'"services/{s}/contracts",')
    ]
    write(root_pp, replace_block(root_pp.read_text(), "workspace-members", members))

    mono = root / "apps" / "monolith" / "pyproject.toml"
    text = replace_block(mono.read_text(), "service-deps", [f'"{s}-service",' for s in services])
    text = replace_block(
        text, "service-sources", [f"{s}-service = {{ workspace = true }}" for s in services]
    )
    write(mono, text)

    write(root / ".importlinter", render_importlinter(services))

    compose = root / "docker-compose.yml"
    text = compose.read_text()
    for marker, lines in compose_blocks(services, root).items():
        text = replace_block(text, marker, lines)
    write(compose, text)
    write(root / "deploy" / "postgres" / "provision.sql", render_provision_sql(services))

    if changed:
        verb = "Out of date" if check else "Updated"
        print(f"{verb}: " + ", ".join(changed))
    return not changed


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    in_sync = sync(ROOT, check=args.check)
    if args.check and not in_sync:
        print("Run: uv run python tools/sync_workspace.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
